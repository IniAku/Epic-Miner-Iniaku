#!/usr/bin/env bash
# Builds epic-miner.toml from the HiveOS flight sheet.
#   Wallet and worker template: %WAL%.%WORKER_NAME%
#   Pool URL:                   us.epic.iniaku.my.id (or id./au.) — anything else = auto
#   Extra config arguments (optional, one per line or space separated):
#     region=auto|id|us|au   amd=0,1   nvidia=0,2   batch=512
#   amd/nvidia pick OpenCL device indexes; "none" disables a vendor. Default: every GPU.

dir=$(dirname "${BASH_SOURCE[0]}")
. "$dir/h-manifest.conf"

[[ -z $CUSTOM_TEMPLATE ]] && echo "CUSTOM_TEMPLATE is empty (set it to %WAL%.%WORKER_NAME%)" && return 1

region=auto
case "$CUSTOM_URL" in
	*id.epic*) region=id ;;
	*us.epic*) region=us ;;
	*au.epic*) region=au ;;
esac
amd= nvidia= batch=
for kv in $CUSTOM_USER_CONFIG; do
	case "$kv" in
		region=*) region=${kv#*=} ;;
		amd=*) amd=${kv#*=} ;;
		nvidia=*) nvidia=${kv#*=} ;;
		batch=*) batch=${kv#*=} ;;
	esac
done

# Default: every AMD / NVIDIA GPU HiveOS detected (OpenCL index = order within the vendor).
detect=${GPU_DETECT_JSON:-/run/hive/gpu-detect.json}
count_brand() { [[ -f $detect ]] && jq "[.[] | select(.brand == \"$1\")] | length" "$detect" 2>/dev/null || echo 0; }
seq_csv() { local n=$1; ((n > 0)) && seq -s, 0 $((n - 1)); }
[[ -z $amd ]] && amd=$(seq_csv "$(count_brand amd)")
[[ -z $nvidia ]] && nvidia=$(seq_csv "$(count_brand nvidia)")
[[ $amd == none ]] && amd=
[[ $nvidia == none ]] && nvidia=

plugins=
add_gpus() { # <platform: 1=AMD 2=NVIDIA> <csv indexes>
	local i
	for i in ${2//,/ }; do
		plugins+="
[[mining.miner_plugin_config]]
plugin_name = \"ocl_cuckatoo\"
[mining.miner_plugin_config.parameters]
platform = $1
device = $i
edge_bits = 19
"
	done
}
add_gpus 1 "$amd"
add_gpus 2 "$nvidia"
[[ -z $plugins ]] && echo "No GPU found for epic-miner (set amd=/nvidia= in Extra config arguments)" && return 1

cat > "$CUSTOM_CONFIG_FILENAME" <<EOF
# Generated by HiveOS h-config.sh — edit the flight sheet instead.
[logging]
log_to_stdout = true
stdout_log_level = "Info"
log_to_file = false
file_log_level = "Info"
log_file_path = "./epic-miner.log"
log_file_append = true

[mining]
algorithm = "Cuckoo"
run_tui = false
region = "$region"
stratum_server_login = "$CUSTOM_TEMPLATE"
stratum_server_password = "${CUSTOM_PASS:-x}"
miner_plugin_dir = "plugins"

[mining.randomx_config]
threads = 1
jit = true
large_pages = false
hard_aes = true
$plugins
EOF

# OCL_BATCH is read by the OpenCL plugin at start (h-run.sh exports it).
echo "${batch}" > "$dir/.ocl_batch"
